import unittest

from postgres import PostgresConnection, postgres_schema


class FakeCursor:
    def __init__(self, rows=()):
        self.rows = list(rows)
        self.rowcount = len(self.rows)

    def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    def fetchall(self):
        rows, self.rows = self.rows, []
        return rows

    def __iter__(self):
        return iter(self.fetchall())


class FakeConnection:
    def __init__(self):
        self.queries = []

    def execute(self, query, args):
        self.queries.append((query, args))
        rows = [{"id": 42}] if "RETURNING id" in query else []
        return FakeCursor(rows)

    def executemany(self, query, args):
        self.queries.append((query, args))
        return FakeCursor()


class PostgresCompatibilityTests(unittest.TestCase):
    def test_schema_converts_sqlite_identity_and_removes_pragma(self):
        schema = postgres_schema(
            "PRAGMA foreign_keys = ON;\n"
            "CREATE TABLE example (id INTEGER PRIMARY KEY AUTOINCREMENT, value INTEGER);"
        )
        self.assertNotIn("PRAGMA", schema)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", schema)
        self.assertIn("value BIGINT", schema)

    def test_placeholders_skip_quoted_question_marks_and_escape_percent(self):
        connection = FakeConnection()
        db = PostgresConnection(connection, {"users"})
        db.execute(
            "SELECT '?' AS literal WHERE value LIKE '%lesson%' AND id=?",
            (7,),
        )
        self.assertEqual(
            connection.queries[0][0],
            "SELECT '?' AS literal WHERE value LIKE '%%lesson%%' AND id=%s",
        )

    def test_unparameterized_query_preserves_percent_patterns(self):
        connection = FakeConnection()
        db = PostgresConnection(connection, {"users"})
        db.execute("SELECT value FROM settings WHERE value LIKE '%lesson%'")
        self.assertEqual(
            connection.queries[0][0],
            "SELECT value FROM settings WHERE value LIKE '%lesson%'",
        )

    def test_insert_ignore_and_generated_id(self):
        connection = FakeConnection()
        db = PostgresConnection(connection, {"users"})
        cursor = db.execute(
            "INSERT OR IGNORE INTO users (username) VALUES (?)",
            ("student",),
        )
        self.assertEqual(
            connection.queries[0][0],
            "INSERT INTO users (username) VALUES (%s) ON CONFLICT DO NOTHING RETURNING id",
        )
        self.assertEqual(cursor.lastrowid, 42)
        self.assertEqual(cursor.fetchone(), {"id": 42})


if __name__ == "__main__":
    unittest.main()
